"""
파일 올리기 안내문 (두 화면 공용).

같은 내용을 두 가지 모양으로 보여줍니다.
  · render_upload_guide_boxes()  : 색깔 박스(빨강+파랑) — 항목 찾기 화면의 업로드 칸 위
  · render_upload_guide()        : 접었다 폈다 — 비교 화면의 노란 주의 박스 아래

문구를 고칠 일이 있으면 이 파일 한 곳만 고치면 두 화면에 같이 반영됩니다.
"""

import streamlit as st

GUIDE_TITLE = "📎 파일 올리기 전에 꼭 읽어보세요 — 스캔본 주의 · 워드를 PDF로 저장하는 법"

SCAN_WARNING = (
    "🚫 **스캔본(사진으로 된) PDF는 읽을 수 없습니다.**\n\n"
    "복사기로 스캔하거나 사진을 찍어 만든 PDF는 겉보기엔 글자 같아도 컴퓨터에는 "
    "**그림 한 장**일 뿐이라 내용을 읽지 못합니다. 화면에 보이는 이미지도 흐릿하게 나옵니다.\n\n"
    "**내 PDF가 어느 쪽인지 1초에 확인하는 법** — PDF를 열어 본문 글자를 마우스로 **드래그**해 보세요. "
    "글자가 파랗게 선택되면 ✅ 그대로 올리면 됩니다. 아무것도 안 잡히고 사진처럼 끌리면 ❌ 스캔본입니다."
)

WORD_TO_PDF = (
    "📄 **워드 파일밖에 없다면 — 워드에서 PDF로 저장한 뒤 그 PDF를 올려주세요.** "
    "이게 가장 정확하고 깨끗합니다.\n\n"
    "**PDF로 저장하는 법 (30초)**\n"
    "1. 그 워드 파일을 **워드로 열기**\n"
    "2. 키보드 **`F12`** 누르기 → 옛날식 저장 창이 뜹니다\n"
    "   (`파일 → 다른 이름으로 저장` 을 누르면 형식 칸이 안 보이는 화면이 먼저 떠서, **F12가 빠릅니다**)\n"
    "3. 아래 **파일 형식** 칸을 눌러 **`PDF (*.pdf)`** 선택\n"
    "4. **저장** → 같은 폴더에 이름이 같고 확장자만 `.pdf` 인 파일이 생깁니다\n"
    "5. 그 **PDF**를 올리면 끝\n\n"
    "*(F12가 안 되면 `파일 → 내보내기 → PDF/XPS 문서 만들기 → 게시` 도 같은 결과입니다)*\n\n"
    "**⚠️ 참고 — 알PDF 같은 무료 변환 프로그램은 권하지 않습니다.** "
    "글자가 깨지거나 통째로 그림으로 저장돼서, 앱이 내용을 못 읽고 형광펜도 안 칠해지는 경우가 있습니다. "
    "**워드에서 직접 저장(F12)** 한 PDF가 가장 정확합니다."
)


def render_upload_guide_boxes():
    """색깔 박스 모양 (항목 찾기 화면)."""
    st.error(SCAN_WARNING)
    st.info(WORD_TO_PDF)


def render_upload_guide(expanded: bool = False):
    """접었다 폈다 하는 모양 (비교 화면). 화면 맨 위에 한 번만 호출."""
    with st.expander(GUIDE_TITLE, expanded=expanded):
        st.markdown(SCAN_WARNING)
        st.divider()
        st.markdown(WORD_TO_PDF)
